"""Print the README 'Demo results' section computed from the committed demo artifacts (no hand-typed numbers)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEMOS = [("HR policy assistant", ROOT / "demos" / "run_hr"), ("Ship-spares procurement assistant", ROOT / "demos" / "run_procurement")]


def j(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def pct(v):
    return "n/a" if v is None else f"{100 * v:.1f}%"


def f3(v):
    return "n/a" if v is None else f"{v:.3f}"


def main() -> None:
    out = ["## Demo results (filled from the committed artifacts)", "",
           "_Generated by `python scripts/demo_summary.py` from `demos/run_*/`. Real local models, see banner at the top._", ""]
    rows = []
    for name, d in DEMOS:
        if not (d / "scorecard_summary.json").exists():
            out.append(f"- {name}: run not available yet")
            continue
        sc = j(d / "scorecard_summary.json")
        base = sc["iterations"][0] if sc["iterations"] else {}
        fin = sc.get("final") or {}
        nc = sc.get("negative_control") or {}
        st = j(d / "judge_selftest.json")
        es = j(d / "eval_set.json")
        req = j(d / "requirements.json")
        agent = j(d / "final_agent.json")
        fails = j(d / "final_eval" / "failure_classification.json")
        entries = [e for it in sorted(d.glob("iter_*")) for e in j(it / "change_log.json")]
        rm = j(d / "run_metrics.json")
        rows.append([name, len(es["cases"]), f"{f3(base.get('dev', {}).get('composite'))} / {f3(base.get('heldout', {}).get('composite'))}",
                     f"{f3(fin.get('dev', {}).get('composite'))} / {f3(fin.get('heldout', {}).get('composite'))}",
                     f3(nc.get("composite")), pct(fin.get("overall", {}).get("pass_rate")),
                     pct(fin.get("overall", {}).get("hallucination_rate")), pct(st.get("judge_v1_accuracy")),
                     f"{sum(e['accepted'] for e in entries)} / {sum(not e['accepted'] for e in entries)}"])
        out += [f"### {name} — [`REPORT.md`]({d.relative_to(ROOT).as_posix()}/REPORT.md)", "",
                f"- removed by the groundability guard (now refused): {req.get('removed_topics')}",
                f"- tools attached: {[t['name'] for t in agent['tools']] or 'none'}",
                f"- remaining failures by category: {fails['by_category']}",
                f"- LLM calls {rm['calls']}, tokens {rm['total_tokens']}, wall time {rm.get('wall_time_s')} s", ""]
    if rows:
        hdr = ["demo", "evals", "v0 composite dev / held-out", "final composite dev / held-out", "negative control",
               "final pass", "halluc.", "judge self-test", "patches accepted / rolled back"]
        out += ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)] + ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    print("\n".join(out))


if __name__ == "__main__":
    main()
